#!/usr/bin/env python3
"""Generate step2/metric_contract.json from real library source.

Run from the repo root after refreshing the two snapshots:

    curl -sL https://raw.githubusercontent.com/huggingface/trl/v0.24.0/trl/trainer/grpo_trainer.py -o /tmp/g24.py
    curl -sL https://raw.githubusercontent.com/unslothai/unsloth/main/unsloth/models/rl_replacements.py -o /tmp/uz_rl.py
    python step2/gen_metric_contract.py

Why this exists: `verdict.py` required `entropy`, which TRL logs and Unsloth's
stack never emits, so a healthy five-step run reported STEP 2 FAIL. Fifty-six
mutants did not catch it, because every `verdict()` test was built from synthetic
log dicts carrying the very assumption under test. `GRPOConfig` kwargs were
checked against vendored source; the metric contract was not. Generated rather
than transcribed so it cannot drift silently into a hand-edited wish list.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

# Unsloth replaces `compute_loss` wholesale. TRL metrics owned by the closures
# inside it are unreachable; metrics owned by `_generate` and
# `_generate_and_score_completions` survive, because Unsloth only guards the
# former for vLLM weight sync and applies targeted string patches to the latter.
DEAD_OWNERS = {"masked_batch_mean", "compute_liger_loss"}

FROM_TRANSFORMERS = ["loss", "grad_norm", "learning_rate", "epoch"]


def _owners(lines: list[str]) -> dict[int, str]:
    cur, out = "<module>", {}
    for i, line in enumerate(lines, 1):
        m = re.match(r"\s*def (\w+)", line)
        if m:
            cur = m.group(1)
        out[i] = cur
    return out


def metric_keys(lines: list[str]) -> dict[str, list[str]]:
    own, acc = _owners(lines), {}
    for i, line in enumerate(lines, 1):
        m = re.search(r'_metrics\[mode\]\["([a-z_/]+)"\]', line)
        if m:
            acc.setdefault(m.group(1), set()).add(own[i])
    return {k: sorted(v) for k, v in sorted(acc.items())}


def build(trl_lines: list[str], unsloth_lines: list[str]) -> dict:
    trl = metric_keys(trl_lines)
    unsloth = metric_keys(unsloth_lines)
    dead = sorted(k for k, o in trl.items() if set(o) <= DEAD_OWNERS)
    alive = sorted(k for k, o in trl.items() if not set(o) <= DEAD_OWNERS)
    return {
        "_comment": "What the Step 2 stack actually logs. GENERATED by step2/gen_metric_contract.py.",
        "_generated": "2026-09-26",
        "_unsloth_pin": "unpinned upstream; snapshot from main on the date above",
        "_dead_reason": (
            "Unsloth replaces compute_loss wholesale, so TRL metrics owned by its inner "
            "masked_batch_mean / compute_liger_loss closures are never reached."
        ),
        "from_transformers_trainer": FROM_TRANSFORMERS,
        "from_trl_survives": alive,
        "from_trl_dead_under_unsloth": dead,
        "from_unsloth_replacement": sorted(unsloth),
    }


def available(contract: dict) -> set[str]:
    """Every metric key a run on this stack can actually emit."""
    return (
        set(contract["from_transformers_trainer"])
        | set(contract["from_trl_survives"])
        | set(contract["from_unsloth_replacement"])
    )


def main() -> int:
    trl = pathlib.Path("/tmp/g24.py")
    uns = pathlib.Path("/tmp/uz_rl.py")
    for p in (trl, uns):
        if not p.exists():
            print(f"missing {p} — see this file's docstring for the curl commands")
            return 1
    contract = build(trl.read_text().splitlines(), uns.read_text().splitlines())
    out = pathlib.Path("step2/metric_contract.json")
    out.write_text(json.dumps(contract, indent=2) + "\n")
    avail = available(contract)
    print(f"wrote {out}")
    print(f"  dead under unsloth : {contract['from_trl_dead_under_unsloth']}")
    print(f"  entropy available  : {'entropy' in avail}")
    for k in ("grad_norm", "completions/mean_length", "reward_std", "kl"):
        print(f"  {k:26} available={k in avail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
